"""Pedagogical 4-node CTQW vs classical random-walk slice of the KRAS
G12C contact core recorded in prior Kytos pre-hackathon work
(experiments/cleveland/c008-moth-qpu-tomography/metrics/graphs/kras_core.json).

Four supernodes of the 20-node KRAS core, in 2-qubit basis index order:
  index 0 = original node 0  (source, P-loop residues 15-21)
  index 1 = original node 3  (connector, residues 114,115,142,143,144,151)
  index 2 = original node 11 (sourceknown, residues 11-14)
  index 3 = original node 8  (known pocket/readout, residues 93-99)
Recorded undirected edges (local indices): (0,1) (0,2) (1,2) (2,3).
Altered-edge control removes (0,2).

The IonQ API accepts only job type ionq.circuit.v1 (a single circuit per
job), so ONE QuantumCircuit(4,4) carries two independent 2-qubit graph
evolutions at the single measured time t=2.0: the recorded-graph
Laplacian on qubits (0,1) and the altered-graph Laplacian on (2,3).
Submitted as one backend.run(single_circuit) call. The printed 5-row
sweep over TIMES is a classical/exact reference, not measurements.
The Qollab runtime pre-creates `backend` and auto-calls main().
"""

import numpy as np
from scipy.linalg import expm
from qiskit import QuantumCircuit, transpile
from qiskit.circuit.library import HamiltonianGate

TIMES = [0.5, 1.0, 1.5, 2.0, 3.0]
MEASURED_TIME = 2.0
RECORDED_EDGES = [(0, 1), (0, 2), (1, 2), (2, 3)]
ALTERED_EDGES = [(0, 1), (1, 2), (2, 3)]
SOURCE = 0
SITE = 3  # 2-qubit basis index '11' within each pair


def adjacency(edges, n=4):
    a = np.zeros((n, n))
    for i, j in edges:
        a[i, j] = a[j, i] = 1.0
    return a


def laplacian(edges):
    a = adjacency(edges)
    return np.diag(a.sum(axis=1)) - a


def classical_site_probability(edges, t):
    a = adjacency(edges)
    q = np.diag(1.0 / a.sum(axis=1)) @ a - np.eye(4)
    return float(np.real(expm(q.T * t)[SITE, SOURCE]))


def ideal_site_probability(edges, t):
    u = expm(-1j * laplacian(edges) * t)
    return float(abs(u[SITE, SOURCE]) ** 2)


def build_circuit():
    qc = QuantumCircuit(4, 4)
    qc.append(HamiltonianGate(laplacian(RECORDED_EDGES), MEASURED_TIME), [0, 1])
    qc.append(HamiltonianGate(laplacian(ALTERED_EDGES), MEASURED_TIME), [2, 3])
    qc.measure([0, 1, 2, 3], [0, 1, 2, 3])
    return qc


def site_marginals(counts, shots):
    recorded = altered = 0
    for bitstr, n in counts.items():
        val = int(bitstr.replace(" ", ""), 2)
        if (val & 0b0011) == 0b0011:
            recorded += n
        if (val & 0b1100) == 0b1100:
            altered += n
    return recorded / shots, altered / shots


def main(shots: int = 2048):
    backend = globals()["backend"]
    qc = transpile(build_circuit(), backend, optimization_level=1)
    counts = backend.run(qc, shots=shots).result().get_counts()
    meas_rec, meas_alt = site_marginals(counts, shots)

    print(
        "Provenance: induced 4-supernode slice of the 20-node KRAS G12C "
        "contact core, recorded in prior pre-hackathon Kytos work "
        "(c008 metrics/graphs/kras_core.json); this is pre-existing "
        "analysis, not a result generated by Qollab."
    )
    print("Edges recorded:", RECORDED_EDGES, "| altered:", ALTERED_EDGES)
    print()
    print(
        "Reference sweep over all fixed times "
        "(exact ideal CTQW vs classical CT RW; classical reference, "
        "not measurements):"
    )
    header = f"{'t':>4} | {'rec ideal':>9} {'rec class':>9} | {'alt ideal':>9} {'alt class':>9}"
    print(header)
    print("-" * len(header))
    for t in TIMES:
        print(
            f"{t:>4.1f} | {ideal_site_probability(RECORDED_EDGES, t):>9.5f} "
            f"{classical_site_probability(RECORDED_EDGES, t):>9.5f} | "
            f"{ideal_site_probability(ALTERED_EDGES, t):>9.5f} "
            f"{classical_site_probability(ALTERED_EDGES, t):>9.5f}"
        )

    print()
    print(
        f"Measured at t={MEASURED_TIME} "
        f"(one job, two independent 2-qubit graph evolutions, 4q total; "
        f"{shots} shots):"
    )
    print(
        f"  recorded: measured {meas_rec:.5f} vs exact "
        f"{ideal_site_probability(RECORDED_EDGES, MEASURED_TIME):.5f}"
    )
    print(
        f"  altered : measured {meas_alt:.5f} vs exact "
        f"{ideal_site_probability(ALTERED_EDGES, MEASURED_TIME):.5f}"
    )
    if meas_alt > meas_rec:
        print(
            "Observation at t=2.0: removing edge (0,2) raises the "
            "measured site probability in this run (altered > recorded)."
        )
    print(
        "Caveats: 4-supernode pedagogical slice, not allosteric site "
        "recovery or a full biological site ranking; a 4-node walk on "
        "noisy or ideal simulation cannot prove recovery of the "
        "biological site; no quantum advantage is claimed; the c008 "
        "Moth graph-v1 run was a different protocol."
    )
    return meas_rec, meas_alt
